/**
 * Scans public/diseases/<slug>/ for generated images (definition.jpg and
 * naturopathic.jpg) and writes src/content/diseases/generated-images.ts — a
 * map DiseaseDetail uses to auto-render those images on generated pages that
 * don't already have an explicit image block. Run after each batch of
 * downloads:
 *
 *   npx vite-node scripts/images/sync-generated-images.ts
 */
import { writeFileSync, existsSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"
import { treatmentAreas } from "@/content/treatments"

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = join(HERE, "..", "..")
const OUT = join(ROOT, "src", "content", "diseases", "generated-images.ts")
const PUB = join(ROOT, "public", "diseases")

const GENERATED_AREAS = new Set([
  "heart-circulation-blood-vessels",
  "musculoskeletal-system-orthopedics-pain-medicine",
  "skin-hair-nails-subcutaneous-tissue",
  "infections-parasitic-diseases",
  "urinary-tract-kidneys",
  "blood-immune-system-oncological-follow-up-care",
  "eyes-sensory-organs",
  "injuries-poisoning-consequences-of-accidents",
])

const rows: string[] = []
let nDef = 0
let nNaturo = 0
for (const area of treatmentAreas) {
  if (!GENERATED_AREAS.has(area.slug)) continue
  for (const d of area.diseases) {
    const def = existsSync(join(PUB, d.slug, "definition.jpg"))
    const naturo = existsSync(join(PUB, d.slug, "naturopathic.jpg"))
    if (!def && !naturo) continue
    const de = d.title.de.replace(/"/g, '\\"')
    const en = d.title.en.replace(/"/g, '\\"')
    rows.push(`  "${d.slug}": { title: { de: "${de}", en: "${en}" }, def: ${def}, naturo: ${naturo} },`)
    if (def) nDef++
    if (naturo) nNaturo++
  }
}

const body = `import type { Loc } from "@/lib/i18n"

/**
 * AUTO-GENERATED by scripts/images/sync-generated-images.ts — do not edit by hand.
 * Which generated images exist per disease slug (under public/diseases/<slug>/).
 * DiseaseDetail renders them (with the KI-generiert caption) on generated pages
 * that have no explicit image block of their own: \`def\` → definition.jpg at the
 * top of the Definition, \`naturo\` → naturopathic.jpg in the naturopathic section.
 */
export type GeneratedImage = { title: Loc; def: boolean; naturo: boolean }

export const generatedImages: Record<string, GeneratedImage> = {
${rows.join("\n")}
}
`

writeFileSync(OUT, body)
console.log(`Wrote ${OUT}: ${nDef} definition + ${nNaturo} naturopathic images.`)
