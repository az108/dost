/**
 * Scans public/diseases/<slug>/definition.jpg and writes
 * src/content/diseases/generated-images.ts — a slug → alt-text map that
 * DiseaseDetail uses to auto-render a generated hero image on any generated
 * page that doesn't already have an explicit image block. Run after each batch
 * of downloads:
 *
 *   npx vite-node scripts/images/sync-generated-images.ts
 */
import { writeFileSync, existsSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"
import { treatmentAreas } from "@/content/treatments"

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = join(HERE, "..", "..")
const OUT = join(ROOT, "src", "content", "diseases", "generated-images.ts")
const PUB = join(ROOT, "public", "diseases")

const GENERATED_AREAS = new Set([
  "heart-circulation-blood-vessels",
  "musculoskeletal-system-orthopedics-pain-medicine",
  "skin-hair-nails-subcutaneous-tissue",
  "infections-parasitic-diseases",
  "urinary-tract-kidneys",
  "blood-immune-system-oncological-follow-up-care",
  "eyes-sensory-organs",
  "injuries-poisoning-consequences-of-accidents",
])

const rows: string[] = []
let n = 0
for (const area of treatmentAreas) {
  if (!GENERATED_AREAS.has(area.slug)) continue
  for (const d of area.diseases) {
    if (!existsSync(join(PUB, d.slug, "definition.jpg"))) continue
    const de = d.title.de.replace(/"/g, '\\"')
    const en = d.title.en.replace(/"/g, '\\"')
    rows.push(`  "${d.slug}": { de: "${de}", en: "${en}" },`)
    n++
  }
}

const body = `import type { Loc } from "@/lib/i18n"

/**
 * AUTO-GENERATED by scripts/images/sync-generated-images.ts — do not edit by hand.
 * Maps a disease slug to its title (used as the alt text) when a generated hero
 * image exists at public/diseases/<slug>/definition.jpg. DiseaseDetail renders
 * it (with the KI-generiert caption) on generated pages that have no explicit
 * image block of their own.
 */
export const generatedImages: Record<string, Loc> = {
${rows.join("\n")}
}
`

writeFileSync(OUT, body)
console.log(`Wrote ${OUT} with ${n} generated images.`)
